tickets_df = pd.read_excel('כרטיסים_לפי_הגרלה.xlsx', sheet_name='כל_הכרטיסים', dtype=str)

prizes = {}
for code in range(1, 57):
    group = tickets_df[tickets_df['קוד הגרלה'] == str(code)]
    p_name = PRIZE_NAMES.get(code, f'הגרלה קוד {code}')
    p_img = f'catalog_rendered_pages/page_{PRIZE_PAGES.get(code, 4)}.png'
    
    t_list = []
    for _, row in group.iterrows():
        t_list.append({
            'ticket_no': int(row['מספר כרטיס']),
            'name': str(row['שם המתפלל']),
            'phone': str(row['טלפון']) if pd.notna(row['טלפון']) else '',
            'pkg': str(row['חבילה']) if pd.notna(row['חבילה']) else ''
        })
    
    prizes[code] = {
        'name': p_name,
        'image': p_img,
        'tickets': t_list
    }

with open('raffle_data.json', 'w', encoding='utf-8') as f:
    json.dump(prizes, f, ensure_ascii=False, indent=2)

